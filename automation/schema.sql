-- Run once in Supabase SQL Editor for AOGx Autonomous Creator.
-- Keep the service-role key only in trusted server/CI secrets; never put it in client code.

create table if not exists public.video_jobs (
  job_key text primary key,
  instruction text not null,
  timezone text not null default 'Asia/Jakarta',
  scheduled_time time not null default '08:00',
  active boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists public.video_runs (
  id bigint generated by default as identity primary key,
  job_key text not null references public.video_jobs(job_key) on delete cascade,
  run_date date not null,
  status text not null default 'queued',
  prompt text,
  title text,
  description text,
  provider_job_id text,
  video_url text,
  youtube_video_id text,
  error text,
  retry_after timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (job_key, run_date)
);

create index if not exists video_runs_status_retry_idx
  on public.video_runs (status, retry_after);

-- These tables should be accessed only by the trusted server/worker service-role key.
alter table public.video_jobs enable row level security;
alter table public.video_runs enable row level security;
grant all on table public.video_jobs, public.video_runs to service_role;
grant usage, select on all sequences in schema public to service_role;
